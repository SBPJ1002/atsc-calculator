constexpr double NaN = __builtin_nan("");

inline CnrResult getCnrValues(int modOrder, int codeRateIdx, int fecType) {
    CnrResult r{};
    r.valid = false;

    if (codeRateIdx < 0 || codeRateIdx > 11) return r;
    if (modOrder < 0 || modOrder > 5) return r;

    bool isLong = (fecType % 2 == 1);

    if (!isLong && modOrder > 3) return r;

    r.valid = true;

    auto safeL = [&](const double table[][12], int mod, int cr) -> double {
        return table[mod][cr];
    };
    auto safeS = [&](const double table[][12], int mod, int cr) -> double {
        if (mod > 3) return NaN;
        return table[mod][cr];
    };

    if (isLong) {
        r.bicm.awgn = safeL(BICM_AWGN_LONG, modOrder, codeRateIdx);
        r.simulation.awgn = safeL(SIM_AWGN_LONG, modOrder, codeRateIdx);
        r.simulation.rc20 = safeL(SIM_RC20_LONG, modOrder, codeRateIdx);
        r.simulation.rl20 = safeL(SIM_RL20_LONG, modOrder, codeRateIdx);
        r.lab.awgn = safeL(LAB_AWGN_LONG, modOrder, codeRateIdx);
        r.lab.rc20 = safeL(LAB_RC20_LONG, modOrder, codeRateIdx);
        r.lab.rl20 = safeL(LAB_RL20_LONG, modOrder, codeRateIdx);
        r.field.awgn = safeL(FIELD_AWGN_LONG, modOrder, codeRateIdx);
        r.field.rc20 = safeL(FIELD_RC20_LONG, modOrder, codeRateIdx);
        r.field.rl20 = safeL(FIELD_RL20_LONG, modOrder, codeRateIdx);
    } else {
        r.bicm.awgn = safeS(BICM_AWGN_SHORT, modOrder, codeRateIdx);
        r.simulation.awgn = safeS(SIM_AWGN_SHORT, modOrder, codeRateIdx);
        r.simulation.rc20 = safeS(SIM_RC20_SHORT, modOrder, codeRateIdx);
        r.simulation.rl20 = safeS(SIM_RL20_SHORT, modOrder, codeRateIdx);
        r.lab.awgn = safeS(LAB_AWGN_SHORT, modOrder, codeRateIdx);
        r.lab.rc20 = safeS(LAB_RC20_SHORT, modOrder, codeRateIdx);
        r.lab.rl20 = safeS(LAB_RL20_SHORT, modOrder, codeRateIdx);
        r.field.awgn = safeS(FIELD_AWGN_SHORT, modOrder, codeRateIdx);
        r.field.rc20 = safeS(FIELD_RC20_SHORT, modOrder, codeRateIdx);
        r.field.rl20 = safeS(FIELD_RL20_SHORT, modOrder, codeRateIdx);
    }

    return r;
}

