// CNR lookup helper - returns NaN if not available
inline double getCnrValue(const double longTable[][12], int longModMax,
                          const double shortTable[][12], int shortModMax,
                          int modOrder, int codeRateIdx, bool isLong) {
    if (codeRateIdx < 0 || codeRateIdx > 11) return NAN;
    if (isLong) {
        if (modOrder < 0 || modOrder >= longModMax) return NAN;
        return longTable[modOrder][codeRateIdx];
    } else {
        if (modOrder < 0 || modOrder >= shortModMax) return NAN;
        return shortTable[modOrder][codeRateIdx];
    }
}

