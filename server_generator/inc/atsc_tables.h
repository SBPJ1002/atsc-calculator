// SP pattern parsing helper (mirrors PHP parseSpLabel)
struct SpInfo {
    int dx;
    std::string group; // "SP3to8" or "SP12to32"
    std::string key;   // e.g. "SP12_2"
};

inline SpInfo parseSpLabel(const std::string& spValue) {
    auto it = SP_PATTERN_MAP.find(spValue);
    std::string spPattern = (it != SP_PATTERN_MAP.end()) ? it->second : "SP12_2";

    // Parse "SPxx_y"
    int dx = 12;
    if (spPattern.size() > 2) {
        size_t underscorePos = spPattern.find('_');
        if (underscorePos != std::string::npos) {
            dx = std::stoi(spPattern.substr(2, underscorePos - 2));
        }
    }

    std::string group = (dx >= 3 && dx <= 8) ? "SP3to8" : "SP12to32";
    return {dx, group, spPattern};
}

// Preamble Dx from preamble_structure (mirrors PHP getPreambleDxFromStructure)
inline int getPreambleDxFromStructure(int preambleStructure) {
    if ((preambleStructure >= 130 && preambleStructure <= 134) ||
        (preambleStructure >= 140 && preambleStructure <= 144)) {
        return 8;
    }
    if ((preambleStructure >= 135 && preambleStructure <= 139) ||
        (preambleStructure >= 145 && preambleStructure <= 149)) {
        return 3;
    }
    return 0; // 0 means "not applicable" (use default dx from table)
}

